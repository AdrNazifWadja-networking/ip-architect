/**
 * DHCP : fonctions pures (aucune base de données) — adresses MAC, durées de bail et génération de configuration.
 * Les fichiers de configuration générés sont techniques : ils restent en anglais, quelle que soit la langue de l'interface.
 */
import { calcSubnet, formatIp, parseIp } from "../ip/cidr";

export type DhcpConfigFormat = "isc" | "cisco";
export const DHCP_CONFIG_FORMATS: readonly DhcpConfigFormat[] = ["isc", "cisco"];

export const MIN_LEASE_SECONDS = 60;
export const MAX_LEASE_SECONDS = 31_536_000; // 365 jours

/** Forme canonique d'une adresse MAC (aa:bb:cc:dd:ee:ff). Accepte « : », « - », « . » ou aucun séparateur. null si invalide. */
export function normalizeMac(input: string): string | null {
  const hex = String(input ?? "")
    .trim()
    .toLowerCase();
  if (!/^([0-9a-f]{2}([:-]?)){5}[0-9a-f]{2}$/.test(hex) && !/^([0-9a-f]{4}\.){2}[0-9a-f]{4}$/.test(hex)) return null;
  const digits = hex.replace(/[^0-9a-f]/g, "");
  if (digits.length !== 12) return null;
  // un séparateur doit rester le même d'un bout à l'autre (« aa:bb-cc… » est refusé)
  const seps = new Set(hex.match(/[:\-.]/g) ?? []);
  if (seps.size > 1) return null;
  return digits.match(/.{2}/g)!.join(":");
}

/** Décompose une durée de bail en jours / heures / minutes / secondes. */
export function splitLease(seconds: number): { d: number; h: number; m: number; s: number } {
  const total = Math.max(0, Math.floor(seconds));
  return {
    d: Math.floor(total / 86_400),
    h: Math.floor((total % 86_400) / 3_600),
    m: Math.floor((total % 3_600) / 60),
    s: total % 60,
  };
}

export interface DhcpConfigScope {
  name: string;
  networkCidr: string;
  rangeStart: string;
  rangeEnd: string;
  gateway: string | null;
  dns: string[];
  leaseSeconds: number;
  enabled: boolean;
}

export interface DhcpConfigReservation {
  mac: string;
  address: string;
  hostname: string | null;
}

/** Nom utilisable dans un fichier de configuration : lettres, chiffres, « - » et « _ » uniquement. */
function token(value: string, fallback: string): string {
  const s = value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^A-Za-z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return s || fallback;
}

/** Noms d'hôte uniques : « pc », « pc-2 », « pc-3 »… (les fichiers de configuration refusent les doublons). */
function uniqueHostNames(reservations: DhcpConfigReservation[]): string[] {
  const seen = new Map<string, number>();
  return reservations.map((r) => {
    const base = token(r.hostname ?? "", `host-${r.mac.replace(/:/g, "")}`);
    const n = (seen.get(base.toLowerCase()) ?? 0) + 1;
    seen.set(base.toLowerCase(), n);
    return n === 1 ? base : `${base}-${n}`;
  });
}

function ipv4Dns(dns: string[]): string[] {
  return dns.filter((d) => parseIp(d)?.version === 4);
}

/** Configuration pour ISC dhcpd (dhcpd.conf). */
export function renderIscConfig(scope: DhcpConfigScope, reservations: DhcpConfigReservation[]): string {
  const info = calcSubnet(scope.networkCidr);
  if (!info || info.version !== 4) return "";
  const dns = ipv4Dns(scope.dns);
  const names = uniqueHostNames(reservations);

  const lines: string[] = [`# Generated by IP Architect - scope "${token(scope.name, "scope")}" (${info.cidr})`];
  if (!scope.enabled) lines.push("# NOTE: this scope is disabled in IP Architect");
  lines.push(`subnet ${info.network} netmask ${info.netmask} {`);
  lines.push(`  range ${scope.rangeStart} ${scope.rangeEnd};`);
  if (scope.gateway) lines.push(`  option routers ${scope.gateway};`);
  if (dns.length) lines.push(`  option domain-name-servers ${dns.join(", ")};`);
  lines.push(`  default-lease-time ${scope.leaseSeconds};`);
  lines.push(`  max-lease-time ${scope.leaseSeconds};`);
  reservations.forEach((r, i) => {
    lines.push("");
    lines.push(`  host ${names[i]} {`);
    lines.push(`    hardware ethernet ${r.mac};`);
    lines.push(`    fixed-address ${r.address};`);
    lines.push("  }");
  });
  lines.push("}");
  return lines.join("\n") + "\n";
}

/** Configuration pour Cisco IOS (pool + adresses exclues + une réservation = un pool « host »). */
export function renderCiscoConfig(scope: DhcpConfigScope, reservations: DhcpConfigReservation[]): string {
  const info = calcSubnet(scope.networkCidr);
  const first = info ? parseIp(info.firstHost) : null;
  const last = info ? parseIp(info.lastHost) : null;
  const start = parseIp(scope.rangeStart);
  const end = parseIp(scope.rangeEnd);
  if (!info || info.version !== 4 || !first || !last || !start || !end) return "";

  const dns = ipv4Dns(scope.dns);
  const poolName = token(scope.name, "POOL");
  const names = uniqueHostNames(reservations);
  // IOS ne sait pas exprimer les secondes : on arrondit à la minute supérieure
  const totalMinutes = Math.ceil(scope.leaseSeconds / 60);
  const leaseDays = Math.floor(totalMinutes / 1440);
  const leaseHours = Math.floor((totalMinutes % 1440) / 60);
  const leaseMinutes = totalMinutes % 60;

  const lines: string[] = [`! Generated by IP Architect - scope "${poolName}" (${info.cidr})`];
  if (!scope.enabled) lines.push("! NOTE: this scope is disabled in IP Architect");

  // tout ce qui est hors de la plage dynamique (passerelle, serveurs…) doit être exclu du pool
  if (start.value > first.value) {
    lines.push(`ip dhcp excluded-address ${info.firstHost} ${formatIp(4, start.value - 1n)}`);
  }
  if (end.value < last.value) {
    lines.push(`ip dhcp excluded-address ${formatIp(4, end.value + 1n)} ${info.lastHost}`);
  }
  lines.push("!");
  lines.push(`ip dhcp pool ${poolName}`);
  lines.push(` network ${info.network} ${info.netmask}`);
  if (scope.gateway) lines.push(` default-router ${scope.gateway}`);
  if (dns.length) lines.push(` dns-server ${dns.join(" ")}`);
  lines.push(` lease ${leaseDays} ${leaseHours} ${leaseMinutes}`);

  reservations.forEach((r, i) => {
    const hex = `01${r.mac.replace(/:/g, "")}`;
    const clientId = hex.match(/.{1,4}/g)!.join(".");
    lines.push("!");
    lines.push(`ip dhcp pool ${poolName}-${names[i]}`);
    lines.push(` host ${r.address} ${info.netmask}`);
    lines.push(` client-identifier ${clientId}`);
    lines.push(` client-name ${names[i]}`);
  });
  return lines.join("\n") + "\n";
}

export function renderDhcpConfig(
  format: DhcpConfigFormat,
  scope: DhcpConfigScope,
  reservations: DhcpConfigReservation[],
): string {
  return format === "cisco" ? renderCiscoConfig(scope, reservations) : renderIscConfig(scope, reservations);
}
