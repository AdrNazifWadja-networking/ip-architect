/**
 * VRF : fonctions pures (aucune base de données) — route distinguisher / route target et génération de configuration.
 * La configuration générée est technique : elle reste en anglais, quelle que soit la langue de l'interface.
 */
import { formatIPv4, parseIPv4 } from "../ip/cidr";

export const MAX_RT_PER_LIST = 8;
const MAX_U16 = 65_535;
const MAX_U32 = 4_294_967_295;

/** Nom de VRF utilisable tel quel dans une configuration réseau : lettres, chiffres, « - » et « _ ». */
export const VRF_NAME_PATTERN = /^[A-Za-z0-9_-]{1,32}$/;

/**
 * Route distinguisher ou route target, forme canonique. null si invalide. Formats acceptés (RFC 4364) :
 *  - ASN:nn   avec ASN sur 2 octets (1-65535) et nn sur 4 octets, ex. 65000:100
 *  - ASN:nn   avec ASN sur 4 octets (65536-4294967295) et nn sur 2 octets, ex. 4200000001:100
 *  - A.B.C.D:nn   avec nn sur 2 octets, ex. 10.0.0.1:100
 */
export function normalizeRouteId(input: string): string | null {
  const parts = String(input ?? "")
    .trim()
    .split(":");
  if (parts.length !== 2) return null;
  const [left, right] = parts;
  if (!/^\d{1,10}$/.test(right)) return null;
  const nn = Number(right);

  if (left.includes(".")) {
    const ip = parseIPv4(left);
    return ip !== null && nn <= MAX_U16 ? `${formatIPv4(ip)}:${nn}` : null;
  }
  if (!/^\d{1,10}$/.test(left)) return null;
  const asn = Number(left);
  if (asn < 1 || asn > MAX_U32) return null;
  if (asn <= MAX_U16) return nn <= MAX_U32 ? `${asn}:${nn}` : null;
  return nn <= MAX_U16 ? `${asn}:${nn}` : null;
}

/** Découpe une saisie « a, b c;d » (ou un tableau) en éléments non vides. */
export function splitList(input: string | string[] | undefined | null): string[] {
  const items = Array.isArray(input) ? input : String(input ?? "").split(/[\s,;]+/);
  return items.map((x) => String(x).trim()).filter(Boolean);
}

export interface VrfConfigInput {
  name: string;
  rd: string | null;
  rtImport: string[];
  rtExport: string[];
  description: string | null;
  /** Adresses IPv6 présentes dans la VRF : ajoute la famille d'adresses IPv6. */
  hasIpv6: boolean;
  /** Réseaux rattachés, listés en commentaire pour garder la trace du plan d'adressage. */
  networks: { cidr: string; name: string }[];
}

/** Texte sur une seule ligne ASCII (une configuration réseau n'aime ni les retours à la ligne ni les accents). */
function oneLine(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^\x20-\x7e]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Configuration Cisco IOS-XE (`vrf definition`). Les route-targets exigent un RD : sans RD, c'est une VRF-Lite. */
export function renderCiscoVrf(v: VrfConfigInput): string {
  const lines: string[] = [`! Generated by IP Architect - VRF "${v.name}"`];
  for (const n of v.networks) lines.push(`! network ${n.cidr} (${oneLine(n.name) || "-"})`);
  lines.push(`vrf definition ${v.name}`);
  const desc = v.description ? oneLine(v.description) : "";
  if (desc) lines.push(` description ${desc}`);
  if (v.rd) lines.push(` rd ${v.rd}`);
  else lines.push(" ! no route distinguisher: VRF-Lite, route-targets are not available");

  const families = v.hasIpv6 ? ["ipv4", "ipv6"] : ["ipv4"];
  for (const fam of families) {
    lines.push(" !");
    lines.push(` address-family ${fam}`);
    if (v.rd) {
      for (const rt of v.rtExport) lines.push(`  route-target export ${rt}`);
      for (const rt of v.rtImport) lines.push(`  route-target import ${rt}`);
    }
    lines.push(" exit-address-family");
  }
  return lines.join("\n") + "\n";
}
