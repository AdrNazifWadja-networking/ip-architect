import { test } from "node:test";
import assert from "node:assert/strict";
import { normalizeRouteId, renderCiscoVrf, splitList, VRF_NAME_PATTERN } from "./rd";

test("normalizeRouteId : formats valides (RFC 4364)", () => {
  assert.equal(normalizeRouteId("65000:100"), "65000:100");
  assert.equal(normalizeRouteId("  65000:100 "), "65000:100");
  assert.equal(normalizeRouteId("65000:0100"), "65000:100"); // zéros inutiles retirés
  assert.equal(normalizeRouteId("1:4294967295"), "1:4294967295"); // ASN 2 octets : numéro sur 4 octets
  assert.equal(normalizeRouteId("4200000001:100"), "4200000001:100"); // ASN 4 octets : numéro sur 2 octets
  assert.equal(normalizeRouteId("10.0.0.1:100"), "10.0.0.1:100");
  assert.equal(normalizeRouteId("10.0.0.1:65535"), "10.0.0.1:65535");
});

test("normalizeRouteId : formats invalides", () => {
  for (const bad of [
    "",
    "65000",
    "65000:",
    ":100",
    "65000:100:1",
    "0:100", // ASN 0 réservé
    "4294967296:1", // ASN trop grand
    "65000:4294967296", // numéro trop grand pour un ASN 2 octets
    "4200000001:65536", // numéro trop grand pour un ASN 4 octets
    "10.0.0.1:65536", // numéro trop grand pour une IPv4
    "10.0.0.256:1",
    "10.0.0:1",
    "abc:1",
    "65000:-1",
    "65000:1.5",
    "65000: 100",
  ]) {
    assert.equal(normalizeRouteId(bad), null, JSON.stringify(bad));
  }
});

test("splitList accepte virgules, espaces, retours à la ligne et tableaux", () => {
  assert.deepEqual(splitList("a, b  c;d\ne"), ["a", "b", "c", "d", "e"]);
  assert.deepEqual(splitList([" a ", "", "b"]), ["a", "b"]);
  assert.deepEqual(splitList(undefined), []);
  assert.deepEqual(splitList(""), []);
});

test("nom de VRF : lettres, chiffres, - et _", () => {
  for (const ok of ["CORP", "vrf-1", "Mgmt_2", "a".repeat(32)]) assert.ok(VRF_NAME_PATTERN.test(ok), ok);
  for (const bad of ["", "avec espace", "é", "a".repeat(33), "x/y", "x;y"]) assert.ok(!VRF_NAME_PATTERN.test(bad), bad);
});

const base = {
  name: "CORP",
  rd: "65000:10",
  rtImport: ["65000:10", "65000:40"],
  rtExport: ["65000:10"],
  description: "Utilisateurs\net serveurs é",
  hasIpv6: false,
  networks: [{ cidr: "10.1.10.0/24", name: "LAN Été" }],
};

test("configuration Cisco IOS-XE", () => {
  const out = renderCiscoVrf(base);
  assert.match(out, /^! Generated by IP Architect - VRF "CORP"\n/);
  assert.match(out, /! network 10\.1\.10\.0\/24 \(LAN Ete\)\n/); // accents retirés
  assert.match(out, /vrf definition CORP\n description Utilisateurs et serveurs e\n rd 65000:10\n/); // une seule ligne ASCII
  assert.match(out, / address-family ipv4\n  route-target export 65000:10\n  route-target import 65000:10\n  route-target import 65000:40\n exit-address-family\n/);
  assert.doesNotMatch(out, /address-family ipv6/);
});

test("Cisco : IPv6 si la VRF en contient, VRF-Lite sans RD (aucun route-target)", () => {
  assert.match(renderCiscoVrf({ ...base, hasIpv6: true }), / address-family ipv6\n/);
  const lite = renderCiscoVrf({ ...base, rd: null, description: null });
  assert.doesNotMatch(lite, /\n  route-target|\n rd |\n description/);
  assert.match(lite, /VRF-Lite/);
});
